/** 按长度降序排好的前缀表（长前缀优先命中，见 FUND_COMPANIES 的注释） */
const COMPANY_PREFIXES: readonly string[] = [...FUND_COMPANIES].sort(
  (a, b) => b.length - a.length,
);

/**
 * 尾部噪音：按数组顺序**从上往下试**，命中一条就剥一条，整个列表反复跑到不再变化。
 *
 * 顺序有讲究，改之前先想清楚这两条：
 *   - 括号载体（`(LOF)`）要排在份额类别前：`…指数(LOF)B` 先掉 B 再掉括号，反过来会
 *     卡在 `…指数(LOF)` 上（括号没被识别，B 也掉了）
 *   - 载体词要排在单个字母前：`纳斯达克100ETF` 若先剥字母会变成 `纳斯达克100ET`，
 *     那是把 ETF 拆了而不是剥了
 */
const NOISE_SUFFIXES: readonly RegExp[] = [
  // 括号里的载体标记：(LOF) / （QDII） / (FOF) / (ETF) / 美元现汇 之类
  /[（(](?:LOF|QDII|FOF|ETF|A类|B类|C类|人民币|美元[^）)]*)[）)]$/i,
  // 载体词：ETF联接 A / ETF发起式联接 / 发起式 / 联接 / ETF / LOF / FOF / QDII
  /(?:ETF发起式联接|ETF发起联接|LOF发起式联接|发起式联接|ETF联接|LOF联接|发起式|联接|ETF|LOF|FOF|QDII)$/i,
  // 币种：人民币份额 / 美元份额
  /(?:人民币|美元现汇|美元现钞|美元)$/,
  // 产品类型词：只剥「这是什么形态」，不碰指数名（`指数` 只是载体说明，剥掉）
  /(?:证券投资基金|灵活配置|指数型|指数|股票型|股票|混合型|混合|债券型|债券|基金)$/,
  // 份额类别：单个字母（A/B/C/D/E/I 等）。放最后一档，理由见本数组顶注
  /[A-Z]$/,
];

/** 剥一轮尾部噪音；没得剥就原样返回（外层靠「返回值没变」来判断收敛） */
function stripNoiseOnce(s: string): string {
  for (const re of NOISE_SUFFIXES) {
    if (re.test(s))
      return s.replace(re, "").trim();
  }
  return s;
}

/**
 * 全称 → 简称。
 *
 * 例（这几个都写在 tests/domain/fund-name.test.ts 里，改规则先看那边红没红）：
 *   博时标普500ETF联接A           → 标普500
 *   景顺长城中证港股通科技ETF发起联接A → 中证港股通科技
 *   招商中证白酒指数               → 中证白酒
 *   中金中证优选300指数(LOF)B       → 中证优选300
 *
 * 剥到只剩一两个字（或本来就为空）时**退回全称**：简称再长也是读者认得的东西，
 * 而 `ETF` 这种残片比全称更看不懂。
 */
export function fundShortName(fullName: string): string {
  const original = fullName.trim();
  if (original === "")
    return "";

  // 头部：剥一个已知的基金公司前缀（只剥一次——公司名不会叠两层）
  let s = original;
  const company = COMPANY_PREFIXES.find(c => s.startsWith(c) && s.length > c.length);
  if (company)
    s = s.slice(company.length);

  // 尾部：反复剥到不再变化。给 10 轮硬顶——199 层后缀是写错了，不是数据长
  for (let i = 0; i < 10; i++) {
    const next = stripNoiseOnce(s);
    if (next === s)
      break;
    s = next;
  }

  s = s.trim();
  return s.length >= 2 ? s : original;
}

/**
 * 简称覆盖表（6 位基金代码 → 要显示的字），**默认空**。
 *
 * 只在自动缩写的口味不对时用：机器剥出来的通常没错，但偶尔会把读者想看到的那半截
 * 剥掉（如把「中证医疗」剥成「医疗」）。往这里加一行就能单独改一只，不必动规则。
 * 空白串会被忽略（当作没登记）。
 */
export const FUND_SHORT_NAME_OVERRIDES: Record<string, string> = {};

/** 取简称：先看覆盖表，没有就自动缩。返回的串一定非空 */
export function fundShortLabel(fundCode: string, fullName: string): string {
  const override = FUND_SHORT_NAME_OVERRIDES[fundCode]?.trim();
  if (override)
    return override;
  return fundShortName(fullName);
}
