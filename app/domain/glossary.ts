/** 按 slug 取词条;落空返回 undefined(详情页据此 throw 404) */
export function getTermBySlug(slug: string): GlossaryTerm | undefined {
  return GLOSSARY_TERMS.find(t => t.slug === slug);
}

/** 取某分类下全部词条(保持 GLOSSARY_TERMS 顺序) */
export function listTermsByCategory(cat: GlossaryCategory): GlossaryTerm[] {
  return GLOSSARY_TERMS.filter(t => t.category === cat);
}

/**
 * 模糊搜索:名称 + 缩写 + slug + 别名,大小写无关。
 * 空串(或纯空白)返回全部——由调用方决定是否展示全量。
 */
export function searchTerms(query: string): GlossaryTerm[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return [...GLOSSARY_TERMS];
  }
  return GLOSSARY_TERMS.filter((t) => {
    const hay = [t.name, t.abbr ?? "", t.slug, ...(t.aliases ?? [])]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}
